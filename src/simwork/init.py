"""`simwork init` — scaffold a working SimWork starter in a directory.

Phase 4, task 1. Generates the starter a developer needs to add SimWork
to a harness in minutes (spec §4): a `simwork.yaml` config, a YAML
scenario for the scripted LLM, and an eval suite (a recorded trace +
a pytest file that gates on it), plus a starter README with the exact
commands to run. The pre-made AI configuration prompt and the LangGraph
demo land in later Phase 4 slices.

The generated files are self-validated before anything is written:
the scenario must parse (`load_scenario`) and the trace must pass the
$0 eval gate (`evaluate_run`), so `init` can never scaffold a broken
starter. Fails closed on collisions: existing files owned by `init`
are only overwritten with `--force`; other files in the target
directory (e.g. the user's harness) are never touched.
"""

from __future__ import annotations

import json
from pathlib import Path

from simwork.eval import evaluate_run, validate_trace
from simwork.llm import parse_scenario

