# Files `init` owns, in the order they are created (and reported).
OWNED_FILES: tuple[tuple[str, str], ...] = (
    ("simwork.yaml", _CONFIG_YAML),
    ("scenarios/ticket-status.yaml", _SCENARIO_YAML),
    ("evals/ticket-status-trace.json", json.dumps(_TRACE, indent=2) + "\n"),
    ("tests/test_simwork_eval.py", _EVAL_TEST_PY),
    ("README.md", _README_MD),
)


class InitError(ValueError):
    """Raised when `simwork init` cannot scaffold the target directory."""


def init_project(target: str | Path, *, force: bool = False) -> list[Path]:
    """Scaffold the SimWork starter in `target`; return the files created.

    Validates the generated scenario + trace before writing anything.
    Refuses to overwrite files `init` owns unless `force` is set, and
    never touches other files in the target directory.
    """
    target = Path(target)
    if target.exists() and not target.is_dir():
        raise InitError(f"init target {target} is not a directory")
    # Self-validate the templates first: a broken starter must fail
    # before any file is written.
    parse_scenario(_SCENARIO_YAML, source="scenarios/ticket-status.yaml")
    report = evaluate_run(validate_trace(_TRACE, source="evals/ticket-status-trace.json"))
    if not report.passed:
        raise InitError(f"starter trace does not pass the eval gate:\n{report.to_text()}")
    collisions = [rel for rel, _ in OWNED_FILES if (target / rel).exists()]
    if collisions and not force:
        raise InitError(
            "file(s) already exist: "
            + ", ".join(collisions)
            + " (re-run with --force to overwrite)"
        )
    target.mkdir(parents=True, exist_ok=True)
    created = []
    for rel, content in OWNED_FILES:
        path = target / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        created.append(path)
    return created
